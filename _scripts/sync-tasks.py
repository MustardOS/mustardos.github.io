#!/usr/bin/env python3
# Builds _data/tasks.yml from the Task Toolkit scripts so the Task Toolkit page lists what the device ships

import pathlib
import re
import sys

internal = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "../internal")
root = internal / "share/task"
if not root.is_dir():
    sys.exit(f"Task folder not found: {root}")

notes_path = pathlib.Path(__file__).resolve().parent.parent / "_data/task_notes.yml"
notes = {}
if notes_path.exists():
    for line in notes_path.read_text().splitlines():
        match = re.match(r'^"([^"]+)":\s*(.+)$', line)
        if match:
            notes[match.group(1)] = match.group(2).strip()


def header(text, key):
    match = re.search(rf"^# {key}:\s*(.*)$", text, re.M)
    return match.group(1).strip() if match else ""


def quote(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


groups = {}
for script in sorted(root.rglob("*.sh")):
    relative = script.relative_to(root)
    group = relative.parent.as_posix() if relative.parent.as_posix() != "." else ""
    text = script.read_text(errors="replace")
    name = script.stem
    help_text = header(text, "HELP")
    if help_text.lower().startswith(name.lower() + " - "):
        help_text = help_text[len(name) + 3:]
    groups.setdefault(group, []).append({
        "name": name,
        "path": relative.as_posix(),
        "icon": header(text, "ICON") or "task",
        "mode": (header(text, "EXECUTION_MODE") or "terminal").lower(),
        "cancel": header(text, "CAN_CANCEL") == "1" and header(text, "NEVER_CANCEL") != "1",
        "desc": notes.get(relative.as_posix(), help_text),
    })

lines = ["# Generated by _scripts/sync-tasks.py from internal/share/task, do not edit by hand", ""]
for group in sorted(groups, key=lambda value: (value != "", value)):
    lines.append(f"- group: {quote(group)}")
    lines.append("  tasks:")
    for task in groups[group]:
        lines.append(f"    - name: {quote(task['name'])}")
        lines.append(f"      path: {quote(task['path'])}")
        lines.append(f"      icon: {quote(task['icon'])}")
        lines.append(f"      mode: {quote(task['mode'])}")
        lines.append(f"      cancel: {'true' if task['cancel'] else 'false'}")
        lines.append(f"      desc: {quote(task['desc'])}")

target = pathlib.Path(__file__).resolve().parent.parent / "_data/tasks.yml"
target.write_text("\n".join(lines) + "\n")
print(f"Wrote {sum(len(tasks) for tasks in groups.values())} tasks in {len(groups)} groups to {target}")
